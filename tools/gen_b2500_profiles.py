#!/usr/bin/env python3
"""Generate the B2500 v2 device profiles in examples/fc41d/devices/.

The profiles are plain ESPHome YAML packages for the hame_device component;
this script only exists because the schedule (time periods) needs one command
template per setting that resends all five periods. Edit here, then run:

    python3 tools/gen_b2500_profiles.py

Field meanings, transforms and commands follow hm2mqtt (src/device/b2500Base.ts,
src/device/b2500V2.ts), which is the reference for the protocol.
"""

from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "examples" / "fc41d" / "devices"

HEADER = """\
# {title}
# Generated by tools/gen_b2500_profiles.py from hm2mqtt's device definition;
# edit the generator, not this file.
#
# Use as a package on a hame_device hub you define yourself:
#   packages:
#     {pkg}: !include {{file: devices/{file}, vars: {{device: battery}}}}
"""


def q(s: str) -> str:
    return '"' + s.replace('"', '\\"') + '"'


def entity(platform: str, name: str, body: dict, extra: list[str] | None = None) -> str:
    lines = [f"  - platform: hame_device", f"    hame_device_id: ${{device}}", f"    name: {q(name)}"]
    for k, v in body.items():
        if v is None:
            continue
        if isinstance(v, bool):
            v = "true" if v else "false"
        elif isinstance(v, list):
            v = "[" + ", ".join(q(str(x)) for x in v) + "]"
        elif isinstance(v, dict):
            inner = "\n".join(f"      {q(str(a))}: {q(str(b))}" for a, b in v.items())
            lines.append(f"    {k}:\n{inner}")
            continue
        elif isinstance(v, str):
            v = q(v)
        lines.append(f"    {k}: {v}")
    for e in extra or []:
        lines.append(f"    {e}")
    return "\n".join(lines)


def section(platform: str, entities: list[str]) -> str:
    return f"{platform}:\n" + "\n\n".join(entities) + "\n"


def power(name, key, **kw):
    return entity("sensor", name, {"key": key, "unit_of_measurement": "W", "device_class": "power",
                                   "state_class": "measurement", "accuracy_decimals": 0, **kw})


CT = {"valid_min": -59999, "valid_max": 59999}  # >= 60000 (e.g. 65535): no reading


def main():
    OUT.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------ runtime
    sensors = [
        entity("sensor", "Battery Percentage", {"key": "pe", "valid_min": 0, "valid_max": 100,
               "unit_of_measurement": "%", "device_class": "battery", "state_class": "measurement",
               "accuracy_decimals": 0}),
        entity("sensor", "Battery Capacity", {"key": "kn", "unit_of_measurement": "Wh",
               "device_class": "energy_storage", "state_class": "measurement", "accuracy_decimals": 0}),
        power("Input 1 Power", "w1"),
        power("Input 2 Power", "w2"),
        power("Total Input Power", ["w1", "w2"]),
        power("Output 1 Power", "g1"),
        power("Output 2 Power", "g2"),
        power("Total Output Power", ["g1", "g2"]),
        entity("sensor", "Temperature Min", {"key": "tl", "unit_of_measurement": "°C",
               "device_class": "temperature", "state_class": "measurement", "accuracy_decimals": 0}),
        entity("sensor", "Temperature Max", {"key": "th", "unit_of_measurement": "°C",
               "device_class": "temperature", "state_class": "measurement", "accuracy_decimals": 0}),
        entity("sensor", "WiFi Signal Strength", {"key": "ws", "valid_min": -120, "valid_max": -1,
               "unit_of_measurement": "dBm", "device_class": "signal_strength", "state_class": "measurement",
               "accuracy_decimals": 0, "entity_category": "diagnostic"}),
        entity("sensor", "Host Battery SoC", {"key": "a0", "valid_min": 0, "valid_max": 100,
               "unit_of_measurement": "%", "device_class": "battery", "state_class": "measurement",
               "accuracy_decimals": 0}),
        entity("sensor", "Extra 1 Battery SoC", {"key": "a1", "valid_min": 0, "valid_max": 100,
               "unit_of_measurement": "%", "device_class": "battery", "state_class": "measurement",
               "accuracy_decimals": 0, "disabled_by_default": True}),
        entity("sensor", "Extra 2 Battery SoC", {"key": "a2", "valid_min": 0, "valid_max": 100,
               "unit_of_measurement": "%", "device_class": "battery", "state_class": "measurement",
               "accuracy_decimals": 0, "disabled_by_default": True}),
        # lv is not a setting on v2: it is the current output setpoint (out1 + out2).
        entity("sensor", "Battery Output Threshold", {"key": "lv", "unit_of_measurement": "W",
               "device_class": "power", "accuracy_decimals": 0}),
    ]
    for name, key in [("Daily Battery Charging", "bc"), ("Daily Battery Discharging", "bs"),
                      ("Daily PV Charging", "pt"), ("Daily Micro Reverse Output Power", "it")]:
        sensors.append(entity("sensor", name, {"key": key, "monotonic": True, "unit_of_measurement": "Wh",
                              "device_class": "energy", "state_class": "total_increasing",
                              "accuracy_decimals": 0}))
    sensors += [
        power("CT Automatic Power Size", "sp"),
        power("CT Transmitted Power", "st", **CT),
        power("CT Clip Power 1", "m0", **CT),
        power("CT Clip Power 2", "m1", **CT),
        power("CT Clip Power 3", "m2", **CT),
        # Despite the app's name, this is the B2500's own output (g1 + g2).
        power("Micro Inverter Power", "m3", **CT),
        power("Rated Output Power", "lmo"),
        power("Rated Input Power", "lmi"),
        entity("sensor", "Firmware Version", {"key": "vv", "accuracy_decimals": 0,
               "entity_category": "diagnostic"}),
        entity("sensor", "Firmware Subversion", {"key": "sv", "accuracy_decimals": 0,
               "entity_category": "diagnostic", "disabled_by_default": True}),
    ]

    binary = []
    for n in (1, 2):
        binary.append(entity("binary_sensor", f"Input {n} Charging", {"key": f"p{n}", "bit": 0,
                             "device_class": "power"}))
        # Not reported by the HMJ (B2500-D): disable it there.
        binary.append(entity("binary_sensor", f"Input {n} Pass Through", {"key": f"p{n}", "bit": 1,
                             "device_class": "power"}))
    for n in (1, 2):
        binary.append(entity("binary_sensor", f"Output {n} Active", {"key": f"o{n}", "bit": 0,
                             "device_class": "power"}))
    binary += [
        entity("binary_sensor", "Temperature Charging Alarm", {"key": "tc", "bit": 0, "device_class": "problem"}),
        entity("binary_sensor", "Temperature Discharge Alarm", {"key": "tf", "bit": 0, "device_class": "problem"}),
        entity("binary_sensor", "Battery Pack 1 Connected", {"key": "b1", "bit": 0}),
        entity("binary_sensor", "Battery Pack 2 Connected", {"key": "b2", "bit": 0}),
        entity("binary_sensor", "CT Connected", {"key": "sg", "bit": 0, "device_class": "power"}),
        entity("binary_sensor", "Rated Power Limited", {"key": "lmf", "bit": 0}),
        entity("binary_sensor", "Full Battery Pass-Through", {"key": "fktc", "on_values": ["1"],
               "icon": "mdi:battery-arrow-up", "disabled_by_default": True}),
    ]
    # Pack status, firmware >= 212.17: l0 = host, l1 bits 0-3 extra 2, 4-7 extra 1.
    flags = [("Discharging", "power"), ("Charging", "battery_charging"),
             ("Depth of Discharge", "problem"), ("Undervoltage", "problem")]
    for pack, key, base, hidden in [("Host", "l0", 0, False), ("Extra 1", "l1", 4, True), ("Extra 2", "l1", 0, True)]:
        for i, (flag, dc) in enumerate(flags):
            binary.append(entity("binary_sensor", f"{pack} Battery {flag}", {"key": key, "bit": base + i,
                                 "device_class": dc, "disabled_by_default": hidden or None}))

    texts = [
        entity("text_sensor", "Scene", {"key": "cj", "map": {"0": "Day", "1": "Night", "2": "Dusk/Dawn"}}),
        entity("text_sensor", "CT Status", {"key": "c1", "map": {
            "5": "Preparing to diagnose CT001 (Step 1)", "6": "Preparing to diagnose CT001 (Step 2)",
            "7": "Diagnosing CT001 equipment", "8": "Diagnosing CT001 channel", "9": "Diagnosis timeout",
            "10": "Charging in progress", "11": "Unable to find channel", "12": "Full battery: PV pass-through"},
            "default": "Not in diagnosis"}),
        entity("text_sensor", "CT Type", {"key": "ct_t", "map": {
            "1": "CT001", "2": "CT001.5", "3": "CT002", "4": "Shelly Pro 3EM", "5": "P1 Meter", "6": "CT003",
            "7": "Shelly EM Gen3", "8": "Shelly Pro EM50", "9": "EcoTracker", "10": "SMR-P1", "11": "SMR-IR",
            "12": "SMR-TIC", "13": "TPM2-100CT"}, "default": "None", "disabled_by_default": True}),
        entity("text_sensor", "Phase Detection", {"key": "seq_s", "message": "ct_diagnosis",
               "map": {"0": "Idle", "1": "Detecting", "2": "Failed", "3": "Done"},
               "icon": "mdi:sine-wave", "disabled_by_default": True}),
        entity("text_sensor", "Device Firmware (FC)", {"key": "fc", "entity_category": "diagnostic",
               "disabled_by_default": True}),
    ]

    # Commands: the non-flash codes (17-20), which hm2mqtt uses by default so
    # frequent changes do not wear the battery's flash.
    numbers = [
        entity("number", "Discharge Depth", {"key": "do", "command": "cd=19,md={value}", "min_value": 0,
               "max_value": 100, "step": 1, "unit_of_measurement": "%", "icon": "mdi:battery-arrow-down"}),
    ]
    selects = [
        entity("select", "Charging Mode", {"key": "cs", "command": "cd=17,md={value}", "options": {
            "0": "Simultaneous Charging/Discharging", "1": "Fully Charge Then Discharge"}}),
        # HMJ firmware <= 110 cannot be set to Phase 1 (it starts a detection instead).
        entity("select", "CT Connected Phase", {"key": "c0", "command": "cd=22,md={value}", "options": {
            "0": "Phase 1", "1": "Phase 2", "2": "Phase 3", "3": "All Phases", "255": "Auto-detect"}}),
        entity("select", "Recharge Mode", {"key": "dchrg_t", "message": "ct_diagnosis",
               "command": "cd=27,dchrg={value}", "options": {"0": "Single Phase", "1": "Three Phase"},
               "icon": "mdi:flash", "disabled_by_default": True}),
    ]
    switches = [
        entity("switch", "Adaptive Mode", {"key": "md", "bit": 0, "command": "cd=18,md={value}",
               "icon": "mdi:auto-fix"}),
        # tc_dis=0 means feed-in on. Firmware: HMJ >= 108, others >= 226.
        entity("switch", "Surplus Feed-in", {"key": "tc_dis", "on_values": ["0"],
               "command_on": "cd=31,touchuan_disa=0", "command_off": "cd=31,touchuan_disa=1",
               "icon": "mdi:transfer"}),
    ]
    texts_settable = []

    # Schedule: reported as dN (enabled), eN (start), fN (end), hN (output W);
    # set with cd=20 listing every period as aN/bN/eN/vN. md=0 applies it and
    # turns adaptive mode off. Periods the device does not report are left out.
    report = {"enabled": "d", "start": "e", "end": "f", "output": "h"}
    command = {"enabled": "a", "start": "b", "end": "e", "output": "v"}

    def period(k, field=None):
        parts = []
        for f in ("enabled", "start", "end", "output"):
            parts.append(f"{command[f]}{k}=" + ("{value}" if f == field else "{" + f"{report[f]}{k}" + "}"))
        return ",".join(parts)

    def schedule_cmd(n, field):
        out = "cd=20,md=0"
        for k in range(1, 6):
            if k == n:
                out += "," + period(k, field)
            else:
                out += "[," + period(k) + "]"
        return out

    for n in range(1, 6):
        switches.append(entity("switch", f"Time Period {n} Enabled", {"key": f"d{n}", "bit": 0,
                               "command": schedule_cmd(n, "enabled"), "icon": "mdi:clock-time-four-outline"}))
        texts_settable.append(entity("text", f"Time Period {n} Start Time", {"key": f"e{n}", "time": True,
                                     "command": schedule_cmd(n, "start")}))
        texts_settable.append(entity("text", f"Time Period {n} End Time", {"key": f"f{n}", "time": True,
                                     "command": schedule_cmd(n, "end")}))
        numbers.append(entity("number", f"Time Period {n} Output Value", {"key": f"h{n}",
                              "command": schedule_cmd(n, "output"), "min_value": 0, "max_value": 800, "step": 1,
                              "unit_of_measurement": "W"}))

    buttons = [
        entity("button", "Refresh", {"command": "cd=1", "icon": "mdi:refresh", "disabled_by_default": True}),
        entity("button", "Restart", {"command": "cd=10", "icon": "mdi:restart", "disabled_by_default": True}),
        entity("button", "Factory Reset", {"command": "cd=11", "icon": "mdi:delete-forever",
               "disabled_by_default": True}),
        entity("button", "Phase Diagnosis", {"command": "cd=27,seq_check", "message": "ct_diagnosis",
               "icon": "mdi:sine-wave", "disabled_by_default": True}),
    ]

    main_yaml = HEADER.format(title="Marstek B2500 v2 (HMA, HMF, HMK, HMJ): status, settings and schedule.",
                              pkg="b2500", file="b2500-v2.yaml") + """\
#
# Not included (yet): meter type/MAC setting, time zone, the "use flash
# commands" switch of hm2mqtt (the non-flash codes are used), pass-through
# sensors hidden on HMJ. Add-ons: b2500-v2-electrical.yaml (voltages and
# currents, cd=16), b2500-v2-cells.yaml (cell voltages, cd=13).

hame_device:
  - id: !extend ${device}
    messages:
      - name: runtime
        required_keys: [pe, kn, do, p1, p2, w1, w2, vv, o1, o2, g1, g2]
        poll: "cd=1"
        interval: 60s
      # CT diagnosis, firmware HMJ >= 102, others > 224 (older ones ignore it).
      - name: ct_diagnosis
        required_keys: [dchrg_t, seq_s]
        excluded_keys: [pe]
        poll: "cd=28"
        interval: 300s

""" + "\n".join([section("sensor", sensors), section("binary_sensor", binary), section("text_sensor", texts),
                 section("number", numbers), section("select", selects), section("switch", switches),
                 section("text", texts_settable), section("button", buttons)])
    (OUT / "b2500-v2.yaml").write_text(main_yaml)

    # ------------------------------------------------------- electrical (cd=16)
    def volt(name, key, hidden=False):
        return entity("sensor", name, {"key": key, "message": "electrical", "multiply": 0.001,
                      "unit_of_measurement": "V", "device_class": "voltage", "state_class": "measurement",
                      "accuracy_decimals": 2, "disabled_by_default": hidden or None})

    def amp(name, key, hidden=False):
        return entity("sensor", name, {"key": key, "message": "electrical", "multiply": 0.001,
                      "unit_of_measurement": "A", "device_class": "current", "state_class": "measurement",
                      "accuracy_decimals": 2, "disabled_by_default": hidden or None})

    elec = [volt("Input Voltage 1", "m1"), volt("Input Voltage 2", "m2"),
            amp("Input Current 1", "c1"), amp("Input Current 2", "c2"),
            volt("Output Voltage 1", "i1"), volt("Output Voltage 2", "i2"),
            amp("Output Current 1", "c3"), amp("Output Current 2", "c4"),
            volt("Host Battery Voltage", "bv"), amp("Host Battery Current", "bc"),
            volt("Extra Battery 1 Voltage", "sv", True), amp("Extra Battery 1 Current", "sc", True),
            volt("Extra Battery 2 Voltage", "lv", True), amp("Extra Battery 2 Current", "lc", True)]
    elec_yaml = HEADER.format(title="Marstek B2500 v2 add-on: input, output and battery voltages/currents (cd=16).",
                              pkg="b2500_electrical", file="b2500-v2-electrical.yaml") + """\

hame_device:
  - id: !extend ${device}
    messages:
      - name: electrical
        required_keys: [bb, bv, bc, sb, sv, sc, lb, lv, lc]
        poll: "cd=16"
        interval: 60s

""" + section("sensor", elec)
    (OUT / "b2500-v2-electrical.yaml").write_text(elec_yaml)

    # ------------------------------------------------------------ cells (cd=13)
    hexs = "0123456789abcdef"
    cells = []
    for pack, prefix, hidden in [("host", "a", False), ("extra1", "b", True), ("extra2", "c", True)]:
        keys = [prefix + h for h in hexs]
        for i, key in enumerate(keys):
            cells.append(entity("sensor", f"Cell Voltage {pack} {i + 1:02d}", {"key": key, "message": "cells",
                                "valid_min": 1, "multiply": 0.001, "unit_of_measurement": "V",
                                "device_class": "voltage", "state_class": "measurement", "accuracy_decimals": 3,
                                "disabled_by_default": hidden or None}))
        for agg, label in [("min", "Min Cell Voltage"), ("max", "Max Cell Voltage"),
                           ("spread", "Cell Voltage Difference"), ("average", "Average Cell Voltage")]:
            cells.append(entity("sensor", f"{label} {pack}", {"key": keys, "message": "cells",
                                "aggregate": agg, "ignore_zero": True, "multiply": 0.001,
                                "unit_of_measurement": "V", "device_class": "voltage",
                                "state_class": "measurement", "accuracy_decimals": 3,
                                "disabled_by_default": hidden or None}))
    cells_yaml = HEADER.format(title="Marstek B2500 v2 add-on: cell voltages per pack (cd=13).",
                               pkg="b2500_cells", file="b2500-v2-cells.yaml") + """\

hame_device:
  - id: !extend ${device}
    messages:
      - name: cells
        required_keys: [a0, a1, a2, a3, a4, a5, a6, a7, a8, a9, aa, ab, ac, ad]
        poll: "cd=13"
        interval: 60s

""" + section("sensor", cells)
    (OUT / "b2500-v2-cells.yaml").write_text(cells_yaml)
    print("wrote", ", ".join(p.name for p in sorted(OUT.glob("*.yaml"))))


if __name__ == "__main__":
    main()
